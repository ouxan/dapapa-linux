        public static string T(string key, params object[] args)
        {
            if (Map.TryGetValue(key, out var pair))
            {
                var template = Current == AppLanguage.Turkish ? pair.Tr : pair.En;
                return args.Length > 0 ? string.Format(Culture, template, args) : template;
            }
            return key;
        }

        public static string RecordsCount(int count)
            => Current == AppLanguage.Turkish
                ? $"{count} kayıt"
                : (count == 1 ? "1 record" : $"{count} records");

        public static string IpRangeCount(int count)
            => Current == AppLanguage.Turkish
                ? $"{count} IP"
                : (count == 1 ? "1 IP" : $"{count} IPs");

        public static string ProcessCount(int count)
            => Current == AppLanguage.Turkish
                ? $"{count} işlem"
                : (count == 1 ? "1 process" : $"{count} processes");
    }
